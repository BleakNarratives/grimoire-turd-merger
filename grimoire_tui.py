#!/usr/bin/env python3
"""grimoire_tui — curses console for the Turd Merger results, plus a live ASK.

Views (Tab to cycle):  BUS  ·  ROADMAP  ·  ASK  ·  ABOUT
Keys: j/k or arrows move · Tab switch view · r reload · q quit
      in ASK: i edit prompt · Enter ask the local engine

Stdlib only. Never writes. Reads .grimoire/bus and the roadmap index.

The ASK view talks to grim_serve over 127.0.0.1 and nothing else. It keeps no
copy of the contract module and imports nothing from the engine on purpose:
a client that imports the server cannot tell you whether the server is up. If
no engine answers, it renders the same floor text the engine would have sent,
labelled offline, and every other view keeps working exactly as before.
"""
from __future__ import annotations
import curses
import hashlib
import json
import sys
import textwrap
import urllib.error
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import grimoire_safety as gs  # noqa: E402
import roadmap_map as rm      # noqa: E402

BUS_DIR = Path.home() / ".grimoire" / "bus"
ROOT = Path.cwd()
VIEWS = ("BUS", "ROADMAP", "ASK", "ABOUT")

# Mirrored from grim_serve on purpose. If the two ever disagree, this client
# refuses to render the answer rather than showing a half-contract.
CONTRACT_FIELDS = ("prompt", "response_text", "model_used",
                   "routing_reason", "offline_text")
ENGINE_URL = "http://127.0.0.1:8787/api/ask"
ENGINE_TIMEOUT = 2.0


def offline_text(prompt: str) -> str:
    """Local floor. Identical in spirit to the engine's, generated here so the
    view still renders something honest with no engine on the machine."""
    digest = hashlib.sha256((prompt or "").encode()).hexdigest()[:8]
    return ("OFFLINE — no model answered. This text was not generated by a "
            f"model.\nThe prompt stayed on this machine ({len(prompt or '')} "
            f"chars, sha256 {digest}).")


def validate_contract(obj: object) -> list[str]:
    if not isinstance(obj, dict):
        return ["contract must be an object"]
    problems = [f"missing {k}" for k in CONTRACT_FIELDS if k not in obj]
    problems += [f"not a string: {k}" for k in CONTRACT_FIELDS
                 if k in obj and not isinstance(obj[k], str)]
    return problems


def ask_engine(prompt: str, url: str = ENGINE_URL,
               timeout: float = ENGINE_TIMEOUT) -> dict:
    """POST one prompt to the local engine. Never raises, never blocks long.

    Every failure path returns a full contract with model_used='offline' and a
    routing_reason that names the failure, because a view that cannot render
    is worse than one that says it could not reach the engine.
    """
    def floor(reason: str) -> dict:
        text = offline_text(prompt)
        return {"prompt": prompt, "response_text": text, "model_used": "offline",
                "routing_reason": reason, "offline_text": text}

    if not (prompt or "").strip():
        return floor("no prompt entered")
    body = json.dumps({"prompt": prompt}).encode()
    req = urllib.request.Request(url, data=body, method="POST",
                                 headers={"Content-Type": "application/json",
                                          "Origin": "http://127.0.0.1"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            payload = json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        return floor(f"engine refused the request (HTTP {e.code})")
    except (urllib.error.URLError, OSError, ValueError) as e:
        return floor(f"engine unreachable ({type(e).__name__})")
    problems = validate_contract(payload)
    if problems:
        return floor("engine answered outside the contract: " + ", ".join(problems))
    return payload

# palette: pair ids
C_TITLE, C_OK, C_WARN, C_FLAG, C_DIM, C_ACCENT, C_SEL = 1, 2, 3, 4, 5, 6, 7


def summarize_bus(rows: list[dict]) -> dict[str, int]:
    counts = {"OK": 0, "WARN": 0, "FLAG": 0, "SKIP": 0, "total": len(rows)}
    for r in rows:
        st = r.get("status", "SKIP")
        if st in counts:
            counts[st] += 1
        else:
            counts["SKIP"] += 1
    return counts


def summarize_roadmap(items: list[dict]) -> dict[str, int]:
    done = sum(it.get("done", 0) for it in items)
    total = sum(it.get("total", 0) for it in items)
    completed = sum(1 for it in items if it.get("total") and it.get("done") == it["total"])
    return {
        "roadmaps": len(items),
        "done": done,
        "total": total,
        "completed_roadmaps": completed,
    }


def format_status_line(view_name: str, data_list: list[dict], sel: int) -> str:
    n = len(data_list)
    sel_str = f"#{sel + 1}/{n}" if n > 0 else "#0/0"
    if view_name == "BUS":
        s = summarize_bus(data_list)
        if n == 0:
            return "BUS: 0 entries"
        return f"BUS: {n} entries ({s['OK']} OK, {s['WARN']} WARN, {s['FLAG']} FLAG) · {sel_str}"
    elif view_name == "ROADMAP":
        s = summarize_roadmap(data_list)
        if n == 0:
            return "ROADMAP: 0 maps"
        pct = f"{int(s['done'] / s['total'] * 100)}%" if s["total"] > 0 else "0%"
        return f"ROADMAP: {n} maps ({s['done']}/{s['total']} tasks · {pct}) · {sel_str}"
    elif view_name == "ASK":
        return "ASK: local engine at 127.0.0.1" + (
            "  - offline floor" if (data_list or [{}])[0].get("result", {}).get(
                "model_used") == "offline" else "")
    else:
        return "ABOUT: Turd Merger console"


def format_empty_state(view_name: str) -> list[str]:
    if view_name == "BUS":
        return [
            "── Empty Bus ──",
            "No .bus or .json files found in ~/.grimoire/bus",
            "Run 'grimoire_safety bus' or scan directory to populate.",
            "Press 'r' to reload after adding entries.",
        ]
    elif view_name == "ROADMAP":
        return [
            "── No Roadmaps Found ──",
            "No ROADMAP*.md files found under repository root.",
            "Create a ROADMAP.md or check repository path.",
            "Press 'r' to reload after adding roadmaps.",
        ]
    return []


def format_keyhints(width: int) -> str:
    if width >= 50:
        return " j/k move · Tab view · r reload · q quit "
    elif width >= 30:
        return " j/k:move Tab:view r:reload q:quit "
    else:
        return " j/k Tab r q "


def compute_layout(height: int, width: int) -> dict:
    header_y = 0 if height >= 1 else -1
    status_y = 1 if height >= 6 else -1
    footer_y = height - 1 if height >= 3 else -1
    msg_y = height - 2 if height >= 7 else -1

    if height >= 12:
        detail_h = 3
    elif height >= 10:
        detail_h = 2
    elif height >= 8:
        detail_h = 1
    else:
        detail_h = 0

    if detail_h > 0 and footer_y != -1:
        detail_y = footer_y - (1 if msg_y != -1 else 0) - detail_h
    else:
        detail_y = -1

    list_y = 2 if status_y != -1 else (1 if header_y != -1 else 0)

    bottom_limit = detail_y if detail_h > 0 else (msg_y if msg_y != -1 else (footer_y if footer_y != -1 else height))
    list_h = max(0, bottom_limit - list_y)

    return {
        "header_y": header_y,
        "status_y": status_y,
        "list_y": list_y,
        "list_h": list_h,
        "detail_y": detail_y,
        "detail_h": detail_h,
        "msg_y": msg_y,
        "footer_y": footer_y,
    }


def load_bus() -> list[dict]:
    if not BUS_DIR.is_dir():
        return []
    files = sorted(BUS_DIR.glob("*.bus")) + sorted(BUS_DIR.glob("*.json"))
    return [gs.grade_file(f) for f in files]


def load_roadmaps() -> list[dict]:
    return [rm.parse_roadmap(p, ROOT) for p in rm.find_roadmaps(ROOT)]


def init_colors() -> None:
    curses.start_color()
    curses.use_default_colors()
    curses.init_pair(C_TITLE, curses.COLOR_MAGENTA, -1)
    curses.init_pair(C_OK, curses.COLOR_GREEN, -1)
    curses.init_pair(C_WARN, curses.COLOR_YELLOW, -1)
    curses.init_pair(C_FLAG, curses.COLOR_RED, -1)
    curses.init_pair(C_DIM, curses.COLOR_WHITE, -1)
    curses.init_pair(C_ACCENT, curses.COLOR_CYAN, -1)
    curses.init_pair(C_SEL, curses.COLOR_BLACK, curses.COLOR_CYAN)


def safe_add(win, y: int, x: int, text: str, attr: int = 0) -> None:
    h, w = win.getmaxyx()
    if y < 0 or y >= h or x >= w:
        return
    try:
        win.addnstr(y, x, text, max(0, w - x - 1), attr)
    except curses.error:
        pass


def draw_header(win, view_idx: int, layout: dict) -> None:
    h, w = win.getmaxyx()
    hy = layout["header_y"]
    if hy < 0 or hy >= h:
        return
    safe_add(win, hy, 0, "─" * w, curses.color_pair(C_DIM))
    if w >= 35:
        title = " GRIMOIRE "
        safe_add(win, hy, 2, title, curses.color_pair(C_TITLE) | curses.A_BOLD)
        x = 2 + len(title) + 1
    elif w >= 20:
        title = " G "
        safe_add(win, hy, 1, title, curses.color_pair(C_TITLE) | curses.A_BOLD)
        x = 1 + len(title) + 1
    else:
        x = 1

    for i, v in enumerate(VIEWS):
        label = f" {v} " if w >= 30 else f"{v[:1]}"
        attr = curses.color_pair(C_SEL) | curses.A_BOLD if i == view_idx else curses.color_pair(C_DIM)
        safe_add(win, hy, x, label, attr)
        x += len(label) + 1


def draw_status_bar(win, view_name: str, data_list: list[dict], sel: int, layout: dict) -> None:
    sy = layout["status_y"]
    h, w = win.getmaxyx()
    if sy < 0 or sy >= h:
        return
    st = format_status_line(view_name, data_list, sel)
    safe_add(win, sy, 2, st, curses.color_pair(C_ACCENT))


def draw_footer(win, msg: str, layout: dict) -> None:
    h, w = win.getmaxyx()
    fy = layout["footer_y"]
    my = layout["msg_y"]
    if fy >= 0 and fy < h:
        keys = format_keyhints(w)
        safe_add(win, fy, 0, keys.ljust(w - 1)[: w - 1], curses.color_pair(C_SEL))
    if msg and my >= 0 and my < h:
        safe_add(win, my, 2, msg, curses.color_pair(C_ACCENT))


def bus_row(r: dict) -> tuple[str, int]:
    status = r.get("status", "SKIP")
    attr = {"OK": C_OK, "WARN": C_WARN, "FLAG": C_FLAG}.get(status, C_DIM)
    name = Path(r.get("file", "?")).name
    score = r.get("score", "-")
    return f"{status:<5} {str(score):>5}  {name}", attr


def draw_empty_state(win, view_name: str, layout: dict) -> None:
    lines = format_empty_state(view_name)
    ly = layout["list_y"]
    lh = layout["list_h"]
    h, w = win.getmaxyx()
    for i, line in enumerate(lines):
        if ly + i >= h or i >= lh:
            break
        attr = curses.color_pair(C_TITLE) | curses.A_BOLD if i == 0 else curses.color_pair(C_DIM)
        safe_add(win, ly + i, 2, line, attr)


def draw_bus(win, rows: list[dict], sel: int, top: int, layout: dict) -> None:
    h, w = win.getmaxyx()
    if not rows:
        draw_empty_state(win, "BUS", layout)
        return
    list_y = layout["list_y"]
    list_h = layout["list_h"]
    for i in range(list_h):
        idx = top + i
        if idx >= len(rows):
            break
        text, attr = bus_row(rows[idx])
        line = f"  {text}"
        if idx == sel:
            safe_add(win, list_y + i, 0, line.ljust(w - 1), curses.color_pair(C_SEL) | curses.A_BOLD)
        else:
            safe_add(win, list_y + i, 0, line, curses.color_pair(attr))

    # detail pane
    det_y = layout["detail_y"]
    det_h = layout["detail_h"]
    if 0 <= sel < len(rows) and det_y >= 0 and det_h > 0:
        r = rows[sel]
        safe_add(win, det_y, 2, f"receipt: {'yes' if r.get('receipt') else 'no'}   sha256: {r.get('sha256', '-')}",
                 curses.color_pair(C_DIM))
        findings = r.get("findings", [])
        for j in range(min(det_h - 1, len(findings))):
            f = findings[j]
            safe_add(win, det_y + 1 + j, 2, f"{f['source']}:{f['pattern']} x{f['hits']}",
                     curses.color_pair(C_WARN))


def draw_roadmap(win, items: list[dict], sel: int, top: int, layout: dict) -> None:
    h, w = win.getmaxyx()
    if not items:
        draw_empty_state(win, "ROADMAP", layout)
        return
    list_y = layout["list_y"]
    list_h = layout["list_h"]
    for i in range(list_h):
        idx = top + i
        if idx >= len(items):
            break
        it = items[idx]
        pct = f"{it['done']}/{it['total']}" if it.get("total") else "  -  "
        line = f"  {pct:>7}  {it.get('path', '?')}"
        attr = curses.color_pair(C_OK) if it.get("total") and it["done"] == it["total"] else curses.color_pair(C_DIM)
        if idx == sel:
            safe_add(win, list_y + i, 0, line.ljust(w - 1), curses.color_pair(C_SEL) | curses.A_BOLD)
        else:
            safe_add(win, list_y + i, 0, line, attr)

    det_y = layout["detail_y"]
    det_h = layout["detail_h"]
    if 0 <= sel < len(items) and det_y >= 0 and det_h > 0:
        it = items[sel]
        safe_add(win, det_y, 2, it.get("title", ""), curses.color_pair(C_ACCENT))
        signals = it.get("signals", [])
        for j in range(min(det_h - 1, len(signals))):
            s = signals[j]
            safe_add(win, det_y + 1 + j, 2, s, curses.color_pair(C_DIM))


def draw_ask(win, state: dict, layout: dict) -> None:
    """Prompt, who answered, why, and the text -- in that order.

    routing_reason is shown before the answer on purpose: a reader should see
    whether a model answered before reading what it said.
    """
    h, w = win.getmaxyx()
    y = layout["list_y"]
    limit = w - 4
    if y >= h:
        return

    def put(text: str, attr: int = 0) -> None:
        nonlocal y
        for line in textwrap.wrap(text, max(20, limit)) or [""]:
            if y >= h or y - layout["list_y"] >= layout["list_h"]:
                return
            safe_add(win, y, 2, line, attr)
            y += 1

    put(f"PROMPT > {state.get('prompt') or '(empty - press i to type)'}",
        curses.color_pair(C_ACCENT))
    put("")
    result = state.get("result")
    if not result:
        put("No answer yet. Press Enter to ask, i to edit the prompt.",
            curses.color_pair(C_DIM))
        return
    model = result.get("model_used", "?")
    offline = model == "offline"
    put(f"MODEL   {model}",
        curses.color_pair(C_WARN) if offline else curses.color_pair(C_OK))
    put(f"ROUTING {result.get('routing_reason', '')}", curses.color_pair(C_DIM))
    put("")
    body = result.get("response_text") or result.get("offline_text") or ""
    put(body, curses.color_pair(C_WARN) if offline else curses.color_pair(C_DIM))


def prompt_for_text(stdscr, current: str) -> str:
    """One line of input on the message row. Returns the old value on cancel."""
    h, w = stdscr.getmaxyx()
    if h < 3:
        return current
    y = h - 2
    safe_add(stdscr, y, 0, ("> " + current).ljust(w - 1), curses.color_pair(C_SEL))
    try:
        curses.curs_set(1)
        curses.echo()
        stdscr.move(y, min(2 + len(current), w - 2))
        raw = stdscr.getstr(y, 2, max(1, w - 4))
        text = raw.decode("utf-8", "replace").strip()
    except (curses.error, KeyboardInterrupt):
        text = ""
    finally:
        curses.noecho()
        curses.curs_set(0)
        stdscr.timeout(-1)
    return text or current


def draw_about(win, layout: dict) -> None:
    lines = [
        ("GRIMOIRE · Turd Merger", curses.color_pair(C_TITLE) | curses.A_BOLD),
        ("", 0),
        ("Read-only. Stdlib only. No network unless you run grimoire_safety llm.", curses.color_pair(C_DIM)),
        ("Verdicts: OK / WARN / FLAG  ·  SHIP / HOLD / KILL", curses.color_pair(C_ACCENT)),
        ("Rule: claim without receipt is a flag, not proof.", curses.color_pair(C_WARN)),
    ]
    list_y = layout["list_y"]
    list_h = layout["list_h"]
    h, w = win.getmaxyx()
    for i, (t, a) in enumerate(lines):
        if list_y + i >= h or i >= list_h:
            break
        safe_add(win, list_y + i, 2, t, a)


def main_loop(stdscr) -> None:
    curses.curs_set(0)
    init_colors()
    stdscr.keypad(True)
    view = 0
    sel = {"BUS": 0, "ROADMAP": 0}
    top = {"BUS": 0, "ROADMAP": 0}
    data = {"BUS": load_bus(), "ROADMAP": load_roadmaps()}
    ask_state: dict = {"prompt": "", "result": None}
    msg = ""
    while True:
        stdscr.erase()
        h, w = stdscr.getmaxyx()
        layout = compute_layout(h, w)
        draw_header(stdscr, view, layout)
        name = VIEWS[view]
        if name in ("BUS", "ROADMAP"):
            draw_status_bar(stdscr, name, data[name], sel[name], layout)
        elif name == "ASK":
            draw_status_bar(stdscr, name, [ask_state], 0, layout)
        else:
            draw_status_bar(stdscr, name, [], 0, layout)

        if name == "BUS":
            draw_bus(stdscr, data["BUS"], sel["BUS"], top["BUS"], layout)
        elif name == "ROADMAP":
            draw_roadmap(stdscr, data["ROADMAP"], sel["ROADMAP"], top["ROADMAP"], layout)
        elif name == "ASK":
            draw_ask(stdscr, ask_state, layout)
        else:
            draw_about(stdscr, layout)
        draw_footer(stdscr, msg, layout)
        stdscr.refresh()
        msg = ""
        key = stdscr.getch()
        if key in (ord("q"), 27):
            return
        if key == 9:  # Tab
            view = (view + 1) % len(VIEWS)
        elif key == ord("r"):
            data = {"BUS": load_bus(), "ROADMAP": load_roadmaps()}
            msg = "reloaded"
        elif name == "ASK" and key == ord("i"):
            ask_state["prompt"] = prompt_for_text(stdscr, ask_state["prompt"])
            msg = "prompt set - Enter to ask"
        elif name == "ASK" and key in (10, 13, curses.KEY_ENTER):
            ask_state["result"] = ask_engine(ask_state["prompt"])
            msg = ("answered: " + ask_state["result"]["model_used"])
        elif name in sel and key in (ord("j"), curses.KEY_DOWN):
            n = len(data[name])
            if n:
                sel[name] = min(sel[name] + 1, n - 1)
        elif name in sel and key in (ord("k"), curses.KEY_UP):
            sel[name] = max(sel[name] - 1, 0)
        if name in sel:
            page = max(layout["list_h"], 1)
            if sel[name] < top[name]:
                top[name] = sel[name]
            elif sel[name] >= top[name] + page:
                top[name] = sel[name] - page + 1


def main() -> int:
    if not sys.stdout.isatty():
        print("grimoire_tui: needs an interactive terminal", file=sys.stderr)
        return 2
    curses.wrapper(main_loop)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
